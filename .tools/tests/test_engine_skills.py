"""Regression tests for `.tools/sync/sync_engine_skills.py` and `.tools/sync/refresh_kit_skills.py`.

The generator builds the Chaos Redux engine-system skills from the pinned kit snapshot and the overlays in
`.claude/skill-overlays/`. Every test builds a small repository in a temporary folder, so nothing tracked is
written. The last class also checks the real repository for drift.
Run from the mod root: `python -B .tools/tests/test_engine_skills.py`.
"""

import contextlib
import io
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(TOOLS / "sync"))

import refresh_kit_skills as refresher
import sync_engine_skills as engine

COMMIT = "1234567890abcdef1234567890abcdef12345678"
ALPHA_KIT = (
	"---\nname: hoi4-alpha\ndescription: Kit alpha description.\n---\n\n# Alpha\n\n"
	"See `hoi4-events` and `hoi4_repo_explorer`, not `hoi4-events-extra`, `my-hoi4-events` or events.xlsx.\n"
	"Details are in `references/guide.md`.\n"
)
GUIDE_KIT = "# Guide\n\nUse `hoi4-beta` for the rest.\n"
BETA_KIT = "---\nname: hoi4-beta\ndescription: Kit beta description.\n---\n\n# Beta\n\nPlain beta text.\n"
MAPPING = {
	"generated": ["hoi4-alpha", "hoi4-beta"],
	"skills": {"hoi4-alpha": "chaos-redux-alpha", "hoi4-beta": "chaos-redux-beta", "hoi4-events": "chaos-redux-events"},
	"agents": {"hoi4_repo_explorer": "chaosx_repo_explorer"},
	"instruction_files": {"CLAUDE.md": "CLAUDE.md"},
}
ALPHA_OVERLAY = "---\ndescription: Chaos Redux alpha: rules.\n---\n\n### In Alpha\n\nChaos Redux alpha rule.\n"
BETA_OVERLAY = "---\ndescription: Chaos Redux beta.\n---\n\n### In Beta\n\nChaos Redux beta rule.\n"


def write(path, text):
	path.parent.mkdir(parents=True, exist_ok=True)
	path.write_bytes(text.encode("utf-8"))


def build_repository(root):
	"""A repository with two generated skills: a snapshot with its manifest, a mapping and two overlays."""
	kit = {"hoi4-alpha/SKILL.md": ALPHA_KIT, "hoi4-alpha/references/guide.md": GUIDE_KIT, "hoi4-beta/SKILL.md": BETA_KIT}
	snapshot = root / engine.SNAPSHOT
	for name, text in kit.items():
		write(snapshot / name, text)
	write(snapshot / "mapping.json", json.dumps(MAPPING))
	digests = {name: engine.file_digest(name, text.encode("utf-8")) for name, text in kit.items()}
	write(snapshot / "manifest.json", json.dumps({"kit_commit": COMMIT, "files": digests}))
	write(root / engine.OVERLAYS / "chaos-redux-alpha" / "overlay.md", ALPHA_OVERLAY)
	write(root / engine.OVERLAYS / "chaos-redux-alpha" / "references" / "ledger.md", "# Ledger\n\nOnly in Chaos Redux.\n")
	write(root / engine.OVERLAYS / "chaos-redux-beta" / "overlay.md", BETA_OVERLAY)


class EngineSkillCase(unittest.TestCase):
	def setUp(self):
		temporary = tempfile.TemporaryDirectory()
		self.addCleanup(temporary.cleanup)
		self.root = Path(temporary.name)
		build_repository(self.root)

	def run_tool(self, *arguments):
		output, errors = io.StringIO(), io.StringIO()
		with contextlib.redirect_stdout(output), contextlib.redirect_stderr(errors):
			status = engine.main(["--root", str(self.root), *arguments])
		return status, output.getvalue(), errors.getvalue()

	def skill(self, name, path="SKILL.md"):
		return self.root / engine.SKILLS / name / path

	def generate(self):
		status, _, errors = self.run_tool()
		self.assertEqual((status, errors), (0, ""))


class GeneratedFiles(EngineSkillCase):
	def test_skill_is_frontmatter_provenance_mapped_kit_body_and_overlay(self):
		self.generate()
		expected = (
			"---\nname: chaos-redux-alpha\ndescription: Chaos Redux alpha: rules.\n---\n"
			"<!-- Generated by .tools/sync/sync_engine_skills.py from the kit's hoi4-alpha at 1234567 "
			"and .claude/skill-overlays/chaos-redux-alpha/. Edit the overlay, never this file. -->\n\n"
			"# Alpha\n\n"
			"See `chaos-redux-events` and `chaosx_repo_explorer`, not `hoi4-events-extra`, `my-hoi4-events` or events.xlsx.\n"
			"Details are in `references/guide.md`.\n\n"
			"## Chaos Redux\n\n### In Alpha\n\nChaos Redux alpha rule.\n"
		)
		self.assertEqual(self.skill("chaos-redux-alpha").read_bytes().decode("utf-8"), expected)

	def test_reference_files_are_mapped_and_overlay_references_are_copied(self):
		self.generate()
		self.assertEqual(self.skill("chaos-redux-alpha", "references/guide.md").read_text(encoding="utf-8"),
			"# Guide\n\nUse `chaos-redux-beta` for the rest.\n")
		self.assertEqual(self.skill("chaos-redux-alpha", "references/ledger.md").read_text(encoding="utf-8"),
			"# Ledger\n\nOnly in Chaos Redux.\n")

	def test_skill_without_overlay_text_has_no_chaos_redux_section(self):
		write(self.root / engine.OVERLAYS / "chaos-redux-beta" / "overlay.md", "---\ndescription: Chaos Redux beta.\n---\n")
		self.generate()
		self.assertNotIn("## Chaos Redux", self.skill("chaos-redux-beta").read_text(encoding="utf-8"))

	def test_overlay_reference_cannot_replace_a_kit_file(self):
		write(self.root / engine.OVERLAYS / "chaos-redux-alpha" / "references" / "guide.md", "# Mine\n")
		status, _, errors = self.run_tool()
		self.assertEqual(status, 2)
		self.assertIn("would replace the kit file references/guide.md", errors)
		self.assertFalse((self.root / engine.SKILLS).exists())


class DriftCheck(EngineSkillCase):
	def test_generated_files_that_match_pass_and_check_writes_nothing(self):
		status, output, _ = self.run_tool("--check")
		self.assertEqual(status, 1)
		self.assertIn("Would update .claude/skills/chaos-redux-alpha/SKILL.md", output)
		self.assertFalse((self.root / engine.SKILLS).exists())
		self.generate()
		self.assertEqual(self.run_tool("--check"), (0, "", ""))

	def test_hand_edit_of_a_generated_file_fails_the_check_and_is_not_repaired_by_it(self):
		self.generate()
		edited = self.skill("chaos-redux-alpha")
		text = edited.read_text(encoding="utf-8")
		edited.write_bytes(text.replace("Chaos Redux alpha rule.", "A hand edit.").encode("utf-8"))
		status, output, _ = self.run_tool("--check")
		self.assertEqual(status, 1)
		self.assertEqual(output, "Would update .claude/skills/chaos-redux-alpha/SKILL.md\n")
		self.assertIn("A hand edit.", edited.read_text(encoding="utf-8"))
		self.generate()
		self.assertNotIn("A hand edit.", edited.read_text(encoding="utf-8"))
		self.assertEqual(self.run_tool("--check")[0], 0)

	def test_extra_file_in_a_generated_folder_is_reported_and_deleted_but_other_folders_are_kept(self):
		self.generate()
		stray = self.skill("chaos-redux-alpha", "references/old/notes.md")
		write(stray, "stray\n")
		own = self.root / engine.SKILLS / "chaos-redux-events" / "SKILL.md"
		write(own, "owned by Chaos Redux\n")
		status, output, _ = self.run_tool("--check")
		self.assertEqual((status, output), (1, "Would update .claude/skills/chaos-redux-alpha/references/old/notes.md\n"))
		self.assertTrue(stray.exists())
		self.generate()
		self.assertFalse(stray.exists())
		self.assertFalse(stray.parent.exists())
		self.assertTrue(own.exists())

	def test_crlf_checkout_is_not_drift(self):
		self.generate()
		for path in (self.root / engine.SKILLS).rglob("*.md"):
			path.write_bytes(path.read_bytes().replace(b"\n", b"\r\n"))
		self.assertEqual(self.run_tool("--check")[0], 0)


class OverlayEdit(EngineSkillCase):
	def test_overlay_edit_regenerates_only_that_skill(self):
		self.generate()
		beta = self.skill("chaos-redux-beta")
		beta_before = (beta.read_bytes(), beta.stat().st_mtime_ns)
		write(self.root / engine.OVERLAYS / "chaos-redux-alpha" / "overlay.md", ALPHA_OVERLAY.replace("alpha rule", "alpha rule, edited"))
		status, output, _ = self.run_tool("--check")
		self.assertEqual((status, output), (1, "Would update .claude/skills/chaos-redux-alpha/SKILL.md\n"))
		self.assertEqual(self.run_tool("--skill", "chaos-redux-beta", "--check")[0], 0)
		status, output, _ = self.run_tool("--skill", "chaos-redux-alpha")
		self.assertEqual((status, output), (0, "Updated .claude/skills/chaos-redux-alpha/SKILL.md\n"))
		self.assertIn("alpha rule, edited", self.skill("chaos-redux-alpha").read_text(encoding="utf-8"))
		self.assertEqual((beta.read_bytes(), beta.stat().st_mtime_ns), beta_before)
		self.assertEqual(self.run_tool("--check")[0], 0)

	def test_a_skill_can_be_named_by_its_kit_name_and_an_unknown_name_is_refused(self):
		self.assertEqual(self.run_tool("--skill", "hoi4-beta", "--check")[1], "Would update .claude/skills/chaos-redux-beta/SKILL.md\n")
		status, _, errors = self.run_tool("--skill", "chaos-redux-events")
		self.assertEqual(status, 2)
		self.assertIn("chaos-redux-events is not a generated engine skill", errors)

	def test_overlay_without_a_description_cannot_run(self):
		write(self.root / engine.OVERLAYS / "chaos-redux-alpha" / "overlay.md", "---\nname: x\n---\nText\n")
		status, _, errors = self.run_tool()
		self.assertEqual(status, 2)
		self.assertIn("needs a description", errors)


class SizeLimit(EngineSkillCase):
	def set_limit(self, limit):
		write(self.root / engine.LIMITS, json.dumps({"root_skill_max_bytes": limit}))

	def test_skill_at_the_limit_passes_and_one_byte_over_fails_without_writing(self):
		self.generate()
		size = self.skill("chaos-redux-alpha").stat().st_size
		self.set_limit(size)
		self.assertEqual(self.run_tool("--check")[0], 0)
		self.set_limit(size - 1)
		status, output, errors = self.run_tool("--check")
		self.assertEqual((status, output), (2, ""))
		self.assertIn(f"chaos-redux-alpha/SKILL.md would be {size} bytes, over the {size - 1}-byte limit", errors)
		self.assertIn("move a complete overlay topic into an overlay reference file", errors)

	def test_oversized_skill_stops_the_write_for_every_skill(self):
		self.set_limit(100)
		status, _, errors = self.run_tool()
		self.assertEqual(status, 2)
		self.assertIn("over the 100-byte limit", errors)
		self.assertFalse((self.root / engine.SKILLS).exists())

	def test_moving_the_topic_into_an_overlay_reference_file_fits_the_limit(self):
		topic = "Long topic text. " * 40
		write(self.root / engine.OVERLAYS / "chaos-redux-beta" / "overlay.md", BETA_OVERLAY + "\n" + topic + "\n")
		self.set_limit(900)
		self.assertEqual(self.run_tool("--skill", "chaos-redux-beta", "--check")[0], 2)
		write(self.root / engine.OVERLAYS / "chaos-redux-beta" / "overlay.md",
			BETA_OVERLAY + "\nThe long topic is in [references/topic.md](references/topic.md).\n")
		write(self.root / engine.OVERLAYS / "chaos-redux-beta" / "references" / "topic.md", "# Topic\n\n" + topic + "\n")
		self.assertEqual(self.run_tool("--skill", "chaos-redux-beta")[0], 0)
		self.assertIn(topic.strip(), self.skill("chaos-redux-beta", "references/topic.md").read_text(encoding="utf-8"))


class Snapshot(EngineSkillCase):
	def test_snapshot_that_differs_from_the_manifest_cannot_run(self):
		path = self.root / engine.SNAPSHOT / "hoi4-beta" / "SKILL.md"
		path.write_bytes(path.read_bytes().replace(b"Plain beta text.", b"Edited beta text."))
		status, _, errors = self.run_tool()
		self.assertEqual(status, 2)
		self.assertIn("differs from manifest.json", errors)
		self.assertIn(".tools/kit_skills/hoi4-beta/SKILL.md", errors)
		self.assertFalse((self.root / engine.SKILLS).exists())

	def test_snapshot_file_missing_from_the_manifest_cannot_run(self):
		write(self.root / engine.SNAPSHOT / "hoi4-beta" / "references" / "new.md", "new\n")
		self.assertEqual(self.run_tool("--skill", "chaos-redux-beta")[0], 2)

	def test_refresh_pins_a_kit_commit_and_the_generator_accepts_the_result(self):
		kit = self.root / "kit"
		environment = dict(os.environ, GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@example.test",
			GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@example.test")
		write(kit / ".claude/skills/hoi4-alpha/SKILL.md", ALPHA_KIT)
		write(kit / ".claude/skills/hoi4-alpha/references/guide.md", GUIDE_KIT)
		write(kit / ".claude/skills/hoi4-beta/SKILL.md", BETA_KIT.replace("Plain beta text.", "Newer beta text."))
		for command in (["init", "-q"], ["add", "-A"], ["-c", "commit.gpgsign=false", "commit", "-q", "-m", "kit"]):
			subprocess.run(["git", "-C", str(kit), *command], check=True, capture_output=True, env=environment)
		# The working tree changes after the commit, and the snapshot must still come from the commit.
		(kit / ".claude/skills/hoi4-beta/SKILL.md").write_bytes(b"uncommitted\n")
		with contextlib.redirect_stdout(io.StringIO()):
			status = refresher.main(["--root", str(self.root), "--kit", str(kit), "--commit", "HEAD"])
		self.assertEqual(status, 0)
		pinned = subprocess.run(["git", "-C", str(kit), "rev-parse", "HEAD"], check=True, capture_output=True, text=True).stdout.strip()
		manifest = json.loads((self.root / engine.SNAPSHOT / "manifest.json").read_text(encoding="utf-8"))
		self.assertEqual(manifest["kit_commit"], pinned)
		self.assertIn("Newer beta text.", (self.root / engine.SNAPSHOT / "hoi4-beta" / "SKILL.md").read_text(encoding="utf-8"))
		self.assertEqual(sorted(manifest["files"]), ["hoi4-alpha/SKILL.md", "hoi4-alpha/references/guide.md", "hoi4-beta/SKILL.md"])
		self.generate()
		self.assertIn(f"at {pinned[:7]}", self.skill("chaos-redux-alpha").read_text(encoding="utf-8"))


